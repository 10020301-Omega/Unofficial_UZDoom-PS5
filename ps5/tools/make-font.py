#!/usr/bin/env python3
# PS5-UZDOOM - the launcher's font: code page 437 in 8x16 cells.
#
#   make-font.py <newconsolefont.hex> <output.inc>
#
# Reads the engine's console font (wadsrc/static/newconsolefont.hex: the
# UNI-VGA font, X licence, completed from GNU Unifont, GPL-2.0-or-later with
# the font embedding exception; wadsrc/static/credits/newconsolefont.txt) and
# writes the 256 glyphs of code page 437 as a C array, 16 bytes a glyph.
#
# Copyright 2026 PS5-UZDOOM port contributors
# SPDX-License-Identifier: GPL-3.0-or-later
import sys

# Code page 437's 0x00-0x1F and 0x7F-0xFF as Unicode; 0x20-0x7E are ASCII.
LOW = [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
       0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
       0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
       0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]
HIGH = [0x2302,
        0x00C7, 0x00FC, 0x00E9, 0x00E2, 0x00E4, 0x00E0, 0x00E5, 0x00E7,
        0x00EA, 0x00EB, 0x00E8, 0x00EF, 0x00EE, 0x00EC, 0x00C4, 0x00C5,
        0x00C9, 0x00E6, 0x00C6, 0x00F4, 0x00F6, 0x00F2, 0x00FB, 0x00F9,
        0x00FF, 0x00D6, 0x00DC, 0x00A2, 0x00A3, 0x00A5, 0x20A7, 0x0192,
        0x00E1, 0x00ED, 0x00F3, 0x00FA, 0x00F1, 0x00D1, 0x00AA, 0x00BA,
        0x00BF, 0x2310, 0x00AC, 0x00BD, 0x00BC, 0x00A1, 0x00AB, 0x00BB,
        0x2591, 0x2592, 0x2593, 0x2502, 0x2524, 0x2561, 0x2562, 0x2556,
        0x2555, 0x2563, 0x2551, 0x2557, 0x255D, 0x255C, 0x255B, 0x2510,
        0x2514, 0x2534, 0x252C, 0x251C, 0x2500, 0x253C, 0x255E, 0x255F,
        0x255A, 0x2554, 0x2569, 0x2566, 0x2560, 0x2550, 0x256C, 0x2567,
        0x2568, 0x2564, 0x2565, 0x2559, 0x2558, 0x2552, 0x2553, 0x256B,
        0x256A, 0x2518, 0x250C, 0x2588, 0x2584, 0x258C, 0x2590, 0x2580,
        0x03B1, 0x00DF, 0x0393, 0x03C0, 0x03A3, 0x03C3, 0x00B5, 0x03C4,
        0x03A6, 0x0398, 0x03A9, 0x03B4, 0x221E, 0x03C6, 0x03B5, 0x2229,
        0x2261, 0x00B1, 0x2265, 0x2264, 0x2320, 0x2321, 0x00F7, 0x2248,
        0x00B0, 0x2219, 0x00B7, 0x221A, 0x207F, 0x00B2, 0x25A0, 0x00A0]
CP437 = LOW + list(range(0x20, 0x7F)) + HIGH
assert len(CP437) == 256


def main():
    source, output = sys.argv[1], sys.argv[2]
    glyphs = {}
    with open(source) as file:
        for line in file:
            code, _, bits = line.strip().partition(":")
            if len(bits) == 32:  # 8 pixels wide, 16 rows
                glyphs[int(code, 16)] = bytes.fromhex(bits)
    missing = [f"{cp:02X}" for cp, code in enumerate(CP437) if code not in glyphs and code not in (0, 0x20)]
    if missing:
        sys.exit(f"make-font.py: no 8x16 glyph for code page 437's {' '.join(missing)}")
    with open(output, "w") as file:
        file.write("// Generated by ps5/tools/make-font.py from wadsrc/static/newconsolefont.hex.\n")
        file.write("// Code page 437, 8x16: UNI-VGA (X licence) completed from GNU Unifont\n")
        file.write("// (GPL-2.0-or-later with the font embedding exception).\n")
        for cp, code in enumerate(CP437):
            rows = glyphs.get(code, bytes(16))
            file.write("\t" + ",".join(f"0x{row:02x}" for row in rows) + f", // {cp:02X} U+{code:04X}\n")


main()
